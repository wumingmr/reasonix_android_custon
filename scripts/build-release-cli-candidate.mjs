import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  copyFileSync,
  cpSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(HERE, "..");
const VERSION_RE = /^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$/;
const SHA_RE = /^[0-9a-f]{40}$/;
export const targets = [
  { key: "darwin-arm64", npm: "darwin-arm64", goos: "darwin", goarch: "arm64" },
  { key: "darwin-amd64", npm: "darwin-x64", goos: "darwin", goarch: "amd64" },
  { key: "linux-arm64", npm: "linux-arm64", goos: "linux", goarch: "arm64" },
  { key: "linux-amd64", npm: "linux-x64", goos: "linux", goarch: "amd64" },
  { key: "windows-arm64", npm: "win32-arm64", goos: "windows", goarch: "arm64" },
  { key: "windows-amd64", npm: "win32-x64", goos: "windows", goarch: "amd64" },
];

function sha256(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

export function platformPackage(target, version, candidateSha) {
  return {
    name: `@reasonix/cli-${target.npm}`,
    version,
    description: `reasonix prebuilt binary for ${target.npm}.`,
    os: [target.goos === "windows" ? "win32" : target.goos],
    cpu: [target.goarch === "amd64" ? "x64" : "arm64"],
    files: ["bin/"],
    license: "MIT",
    repository: { type: "git", url: "git+https://github.com/esengine/DeepSeek-Reasonix.git" },
    reasonixCandidateSha: candidateSha,
    gitHead: candidateSha,
  };
}

export function renderHomebrewCask(version, sums) {
  const requireSum = name => {
    if (!/^[0-9a-f]{64}$/.test(sums[name] ?? "")) throw new Error(`missing checksum for ${name}`);
    return sums[name];
  };
  return `# This file was generated by Reasonix release candidate preparation. DO NOT EDIT.
cask "reasonix" do
  postflight_steps do
    if OS.mac?
      system_command "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "#{staged_path}/reasonix"]
    end
  end

  version "${version}"

  on_macos do
    on_arm do
      sha256 "${requireSum("reasonix-darwin-arm64.tar.gz")}"
      url "https://github.com/esengine/DeepSeek-Reasonix/releases/download/v#{version}/reasonix-darwin-arm64.tar.gz"
    end
    on_intel do
      sha256 "${requireSum("reasonix-darwin-amd64.tar.gz")}"
      url "https://github.com/esengine/DeepSeek-Reasonix/releases/download/v#{version}/reasonix-darwin-amd64.tar.gz"
    end
  end
  on_linux do
    on_arm do
      sha256 "${requireSum("reasonix-linux-arm64.tar.gz")}"
      url "https://github.com/esengine/DeepSeek-Reasonix/releases/download/v#{version}/reasonix-linux-arm64.tar.gz"
    end
    on_intel do
      sha256 "${requireSum("reasonix-linux-amd64.tar.gz")}"
      url "https://github.com/esengine/DeepSeek-Reasonix/releases/download/v#{version}/reasonix-linux-amd64.tar.gz"
    end
  end

  name "reasonix"
  desc "Cache-first DeepSeek coding agent for the terminal."
  homepage "https://github.com/esengine/DeepSeek-Reasonix"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "reasonix"
end
`;
}

function run(command, args, options = {}) {
  execFileSync(command, args, { stdio: "inherit", ...options });
}

function makeArchive(target, binary, cliDirectory, work) {
  const stage = path.join(work, `cli-${target.key}`);
  mkdirSync(stage);
  for (const name of ["CHANGELOG.md", "LICENSE", "README.md", "README.zh-CN.md"]) copyFileSync(path.join(ROOT, name), path.join(stage, name));
  copyFileSync(binary, path.join(stage, target.goos === "windows" ? "reasonix.exe" : "reasonix"));
  const extension = target.goos === "windows" ? "zip" : "tar.gz";
  const archive = path.join(cliDirectory, `reasonix-${target.key}.${extension}`);
  if (target.goos === "windows") run("zip", ["-q", "-r", archive, "."], { cwd: stage });
  else run("tar", ["-czf", archive, "-C", stage, "."]);
  return archive;
}

function packNpm(target, binary, npmDirectory, work, version, candidateSha) {
  const stage = path.join(work, `npm-${target.npm}`);
  mkdirSync(path.join(stage, "bin"), { recursive: true });
  copyFileSync(binary, path.join(stage, "bin", target.goos === "windows" ? "reasonix.exe" : "reasonix"));
  writeFileSync(path.join(stage, "package.json"), `${JSON.stringify(platformPackage(target, version, candidateSha), null, 2)}\n`);
  run("npm", ["pack", stage, "--pack-destination", npmDirectory, "--silent"]);
}

function packNpmRoot(npmDirectory, work, version, candidateSha) {
  const stage = path.join(work, "npm-reasonix");
  mkdirSync(stage);
  cpSync(path.join(ROOT, "npm", "reasonix", "bin"), path.join(stage, "bin"), { recursive: true });
  copyFileSync(path.join(ROOT, "README.md"), path.join(stage, "README.md"));
  const pkg = JSON.parse(readFileSync(path.join(ROOT, "npm", "reasonix", "package.json"), "utf8"));
  pkg.version = version;
  pkg.reasonixCandidateSha = candidateSha;
  pkg.gitHead = candidateSha;
  for (const name of Object.keys(pkg.optionalDependencies)) pkg.optionalDependencies[name] = version;
  writeFileSync(path.join(stage, "package.json"), `${JSON.stringify(pkg, null, 2)}\n`);
  run("npm", ["pack", stage, "--pack-destination", npmDirectory, "--silent"]);
}

export function buildCandidate(version, output, env = process.env) {
  if (!VERSION_RE.test(version)) throw new Error("candidate version must be MAJOR.MINOR.PATCH");
  const candidateSha = env.RELEASE_SOURCE_SHA || execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim();
  if (!SHA_RE.test(candidateSha)) throw new Error("candidate source SHA must be full length");
  const buildTime = env.RELEASE_BUILD_TIME;
  if (!buildTime || !Number.isFinite(new Date(buildTime).valueOf())) throw new Error("RELEASE_BUILD_TIME must be an ISO timestamp");
  mkdirSync(output);
  const cliDirectory = path.join(output, "cli");
  const npmDirectory = path.join(output, "npm");
  const binaries = path.join(output, "binaries");
  mkdirSync(cliDirectory); mkdirSync(npmDirectory); mkdirSync(binaries);
  const work = mkdtempSync(path.join(tmpdir(), "reasonix-cli-candidate-"));
  try {
    for (const target of targets) {
      const filename = target.goos === "windows" ? "reasonix.exe" : "reasonix";
      const directory = path.join(binaries, target.key);
      mkdirSync(directory);
      const binary = path.join(directory, filename);
      const ldflags = `-s -w -X main.version=v${version} -X main.gitCommit=${candidateSha.slice(0, 12)} -X main.buildTimeUTC=${buildTime} -X reasonix/internal/productdocs.linkedVersion=v${version} -X reasonix/internal/productdocs.linkedRevision=${candidateSha}`;
      run("go", ["build", "-trimpath", "-ldflags", ldflags, "-o", binary, "./cmd/reasonix"], {
        cwd: ROOT, env: { ...env, CGO_ENABLED: "0", GOOS: target.goos, GOARCH: target.goarch },
      });
      makeArchive(target, binary, cliDirectory, work);
      packNpm(target, binary, npmDirectory, work, version, candidateSha);
    }
    packNpmRoot(npmDirectory, work, version, candidateSha);
    const assets = targets.map(target => `reasonix-${target.key}.${target.goos === "windows" ? "zip" : "tar.gz"}`).sort();
    const sums = Object.fromEntries(assets.map(name => [name, sha256(path.join(cliDirectory, name))]));
    writeFileSync(path.join(cliDirectory, "SHA256SUMS"), `${assets.map(name => `${sums[name]}  ${name}`).join("\n")}\n`);
    writeFileSync(path.join(cliDirectory, "reasonix.rb"), renderHomebrewCask(version, sums));
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const [version, output] = process.argv.slice(2);
  if (!version || !output) throw new Error("usage: build-release-cli-candidate.mjs VERSION OUTPUT");
  buildCandidate(version, path.resolve(output));
}
